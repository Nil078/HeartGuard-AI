"""Model loading, evaluation, and selection helpers. App code never calls .fit()."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    f1_score,
    precision_recall_curve,
    precision_score,
    recall_score,
    roc_auc_score,
    roc_curve,
)

from utils.preprocessing import CATEGORICAL_FEATURES, FEATURE_COLUMNS

PROJECT_ROOT = Path(__file__).resolve().parent.parent
MODEL_PATH = PROJECT_ROOT / "heart_disease_model.pkl"
METADATA_PATH = PROJECT_ROOT / "model_metadata.json"

DISCLAIMER = (
    "This result is generated by a machine-learning model for educational/research "
    "purposes. It is not a medical diagnosis. Please consult a qualified healthcare "
    "professional for medical advice."
)

# Combined selection weights: recall is most important for a screening context.
SELECTION_WEIGHTS = {
    "recall": 0.35,
    "roc_auc": 0.30,
    "f1": 0.20,
    "accuracy": 0.15,
}


def json_safe(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(k): json_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_safe(v) for v in value]
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, (np.bool_, bool)):
        return bool(value)
    if isinstance(value, (np.floating, float)):
        return float(value)
    if isinstance(value, (np.integer, int)):
        return int(value)
    if value is None:
        return None
    return value


def evaluate_model(
    pipeline, X_test: pd.DataFrame, y_test: pd.Series
) -> dict[str, Any]:
    """Test-set metrics, confusion matrix, and curve points. No training."""
    y_pred = pipeline.predict(X_test)
    if hasattr(pipeline, "predict_proba"):
        y_score = pipeline.predict_proba(X_test)[:, 1]
    else:
        y_score = pipeline.decision_function(X_test)

    fpr, tpr, roc_thresholds = roc_curve(y_test, y_score)
    prec, rec, pr_thresholds = precision_recall_curve(y_test, y_score)
    cm = confusion_matrix(y_test, y_pred, labels=[0, 1])

    return {
        "accuracy": float(accuracy_score(y_test, y_pred)),
        "precision": float(precision_score(y_test, y_pred, zero_division=0)),
        "recall": float(recall_score(y_test, y_pred, zero_division=0)),
        "f1": float(f1_score(y_test, y_pred, zero_division=0)),
        "roc_auc": float(roc_auc_score(y_test, y_score)),
        "confusion_matrix": cm.tolist(),
        "roc_curve": {
            "fpr": fpr.tolist(),
            "tpr": tpr.tolist(),
            "thresholds": roc_thresholds.tolist(),
        },
        "pr_curve": {
            "precision": prec.tolist(),
            "recall": rec.tolist(),
            "thresholds": pr_thresholds.tolist(),
        },
    }


def _original_feature_from_transformed(name: str) -> str:
    # ColumnTransformer names: num__age, cat__cp_0, ...
    if name.startswith("num__"):
        return name.split("__", 1)[1]
    if name.startswith("cat__"):
        rest = name.split("__", 1)[1]
        for col in CATEGORICAL_FEATURES:
            if rest == col or rest.startswith(f"{col}_"):
                return col
        return rest
    return name


def extract_feature_importance(pipeline) -> dict[str, Any] | None:
    """Tree importances or logistic coefficients; None if the estimator has neither."""
    model = pipeline.named_steps.get("model", pipeline)
    preprocessor = pipeline.named_steps.get("preprocessor")
    try:
        names = list(preprocessor.get_feature_names_out())
    except Exception:
        names = FEATURE_COLUMNS

    values: np.ndarray | None = None
    method = None
    if hasattr(model, "feature_importances_"):
        values = np.asarray(model.feature_importances_, dtype=float)
        method = "tree"
    elif hasattr(model, "coef_"):
        coef = np.asarray(model.coef_, dtype=float)
        values = coef.ravel()
        method = "coef"
    if values is None:
        return None
    if len(values) != len(names):
        names = [f"feature_{i}" for i in range(len(values))]

    grouped: dict[str, float] = {c: 0.0 for c in FEATURE_COLUMNS}
    for name, val in zip(names, values):
        orig = _original_feature_from_transformed(name)
        grouped[orig] = grouped.get(orig, 0.0) + float(abs(val) if method == "tree" else val)

    return {
        "method": method,
        "features": names,
        "values": [float(v) for v in values],
        "grouped": {k: float(v) for k, v in grouped.items()},
    }


def combined_selection_score(metrics: dict[str, float]) -> float:
    return sum(SELECTION_WEIGHTS[k] * float(metrics[k]) for k in SELECTION_WEIGHTS)


def select_best_model(comparison: dict[str, dict[str, Any]]) -> tuple[str, str]:
    """Pick a model from test metrics (ROC-AUC, recall, F1, accuracy)."""
    ranked = sorted(
        comparison.items(),
        key=lambda item: combined_selection_score(item[1]),
        reverse=True,
    )
    best_name, best = ranked[0]
    rationale = (
        f"Selected {best_name}: combined test-set score emphasizing recall "
        f"(weight {SELECTION_WEIGHTS['recall']:.2f}) together with ROC-AUC "
        f"({SELECTION_WEIGHTS['roc_auc']:.2f}), F1 ({SELECTION_WEIGHTS['f1']:.2f}), "
        f"and accuracy ({SELECTION_WEIGHTS['accuracy']:.2f}). "
        f"Test recall={best['recall']:.4f}, ROC-AUC={best['roc_auc']:.4f}, "
        f"F1={best['f1']:.4f}, accuracy={best['accuracy']:.4f}."
    )
    if len(ranked) > 1:
        runner_name, runner = ranked[1]
        rationale += (
            f" Next was {runner_name} (recall={runner['recall']:.4f}, "
            f"ROC-AUC={runner['roc_auc']:.4f})."
        )
    return best_name, rationale


def load_model(path: Path | None = None):
    model_path = path or MODEL_PATH
    if not model_path.exists():
        return None
    return joblib.load(model_path)


def load_metadata(path: Path | None = None) -> dict[str, Any] | None:
    meta_path = path or METADATA_PATH
    if not meta_path.exists():
        return None
    with open(meta_path, encoding="utf-8") as f:
        return json.load(f)


def artifacts_exist() -> bool:
    return MODEL_PATH.exists() and METADATA_PATH.exists()
